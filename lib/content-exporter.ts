/**
 * 内容导出工具类
 * 用于将数据库内容导出为 Markdown 格式
 */

import db from './db';

/**
 * 格式化日期时间
 */
function formatDateTime(date: Date | string): string {
  const d = typeof date === 'string' ? new Date(date) : date;
  return d.toLocaleString('zh-CN', {
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit'
  });
}

/**
 * 导出撰写计划为 Markdown
 */
export function exportPlanToMarkdown(projectId: number): string {
  try {
    const project = db.prepare('SELECT name FROM projects WHERE id = ?').get(projectId) as any;
    const plan = db.prepare('SELECT * FROM review_plans WHERE project_id = ? ORDER BY created_at DESC LIMIT 1').get(projectId) as any;

    if (!plan) {
      return '';
    }

    return `---
title: 文献综述撰写计划
project: ${project?.name || 'Unknown'}
created: ${plan.created_at}
---

# 文献综述撰写计划

**项目名称：** ${project?.name || 'Unknown'}
**创建时间：** ${formatDateTime(plan.created_at)}

## 计划内容

${plan.plan_content || '暂无内容'}

---
*Generated by Literature Review AI on ${formatDateTime(new Date())}*
`;
  } catch (error) {
    console.error('Failed to export plan:', error);
    return '';
  }
}

