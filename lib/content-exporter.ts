/**
 * 导出关键词为 Markdown
 */
export function exportKeywordsToMarkdown(projectId: number): string {
  try {
    const project = db.prepare('SELECT name FROM projects WHERE id = ?').get(projectId) as any;
    const keywords = db.prepare('SELECT * FROM project_keywords WHERE project_id = ?').all(projectId) as any[];

    if (!keywords || keywords.length === 0) {
      return '';
    }

    const keywordsList = keywords.map(k => `- ${k.keyword}`).join('\n');

    return `---
title: 项目关键词
project: ${project?.name || 'Unknown'}
updated: ${formatDateTime(new Date())}
---

# 项目关键词

**项目名称：** ${project?.name || 'Unknown'}
**更新时间：** ${formatDateTime(new Date())}
**关键词数量：** ${keywords.length}

## 关键词列表

${keywordsList}

---
*Generated by Literature Review AI on ${formatDateTime(new Date())}*
`;
  } catch (error) {
    console.error('Failed to export keywords:', error);
    return '';
  }
}

/**
 * 导出文献搜索结果为 Markdown
 */
export function exportSearchResultsToMarkdown(projectId: number): string {
  try {
    const project = db.prepare('SELECT name FROM projects WHERE id = ?').get(projectId) as any;
    const literature = db.prepare('SELECT * FROM searched_literature WHERE project_id = ? ORDER BY created_at DESC').all(projectId) as any[];

    if (!literature || literature.length === 0) {
      return '';
    }

    const literatureList = literature.map((lit, index) => {
      return `### ${index + 1}. ${lit.title || '无标题'}

- **作者：** ${lit.authors || '未知'}
- **来源：** ${lit.source || '未知'}
- **DOI：** ${lit.doi || '无'}
- **链接：** ${lit.url || '无'}
- **摘要：** ${lit.abstract || '无摘要'}
`;
    }).join('\n');

    return `---
title: 文献搜索结果
project: ${project?.name || 'Unknown'}
updated: ${formatDateTime(new Date())}
---

# 文献搜索结果

**项目名称：** ${project?.name || 'Unknown'}
**搜索时间：** ${formatDateTime(new Date())}
**文献数量：** ${literature.length}

## 文献列表

${literatureList}

---
*Generated by Literature Review AI on ${formatDateTime(new Date())}*
`;
  } catch (error) {
    console.error('Failed to export search results:', error);
    return '';
  }
}
